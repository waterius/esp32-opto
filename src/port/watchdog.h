// Порт: сторож главного цикла и причина последней перезагрузки.
//
// Зачем свой: в arduino-esp32 задача loopTask к сторожу задач не подписана
// (cores/esp32/main.cpp, loopTaskWDTEnabled = false), поэтому зависание внутри
// loop() перезагрузки не вызывает. Подписать её штатно нельзя: esp_task_wdt
// настроен на 5 секунд, а наш HTTPS-запрос законно занимает до 12 — сторож
// срабатывал бы посреди отправки. Поэтому отдельный сторож с большим бюджетом,
// как OsWatch в Tasmota.
#pragma once
#include <stdint.h>

namespace watchdog {

// Запускает сторож. Вызывать в начале setup(): до этого ничего не сторожится.
void begin();

// «Цикл жив» — из конца loop() и из core::sleepMs(), чтобы длинный, но
// исправный обмен со счётчиком не считался зависанием.
void feed();

// Прошлая перезагрузка — работа этого сторожа (метка в RTC переживает сброс).
bool trippedLastBoot();

// Причина последней перезагрузки словами и кодом esp_reset_reason().
const char* resetReason();
uint8_t resetReasonCode();

}  // namespace watchdog
