// Порт: сторожа и причина последней перезагрузки.
//
// Сторожей два, и это не избыточность — они ловят разные отказы.
//
// 1. Сторож главного цикла на esp_timer. Ловит зависание внутри loop(): своя
//    задача проверяет, что цикл тикал. Нужен потому, что в arduino-esp32
//    задача loopTask к сторожу задач не подписана (cores/esp32/main.cpp,
//    loopTaskWDTEnabled = false), а подписать её штатно нельзя: esp_task_wdt
//    настроен на 5 секунд, а наш HTTPS-запрос законно занимает до 12.
//
// 2. RTC WDT. Ловит то, чего первый не ловит в принципе: заклинивание всего
//    планировщика, когда задачи вообще не получают процессор. Тикает в
//    RTC-домене, независимо от ядра, прерываний и FreeRTOS. Такой отказ мы
//    наблюдали на плате: ни лога по USB, ни ответа по сети, при живом питании,
//    и сторож на esp_timer промолчал, потому что его задача тоже не работала.
#pragma once
#include <stdint.h>

#include "../core/restart_reason.h"

namespace watchdog {

// Вызывать в начале setup(): до этого ничего не сторожится.
void begin();

// «Цикл жив» — из конца loop() и из core::sleepMs(), чтобы длинный, но
// исправный обмен со счётчиком не считался зависанием. Кормит обоих сторожей.
void feed();

// Прошлая перезагрузка — работа сторожа цикла (метка в RTC переживает сброс).
bool trippedLastBoot();

// Причина последней перезагрузки словами и кодом esp_reset_reason().
const char* resetReason();
uint8_t resetReasonCode();

// Сторожа запустились? Если нет, об этом сказано в логе при старте.
bool loopWatchdogArmed();
bool rtcWatchdogArmed();

}  // namespace watchdog
