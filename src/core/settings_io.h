// Ядро: настройки ↔ JSON. Носитель записи в NVS (ключ `cfg`, port/storage.*).
//
// Запись самоописательная, поэтому разбор стартует с умолчаний и перекрывает
// только те ключи, что в ней есть: новое поле берёт умолчание само, удалённое
// молча игнорируется, версия при этом не двигается. SETTINGS_VERSION растёт
// только на смену смысла уже существующего поля — и тогда в settings_io.cpp
// появляется функция апгрейда на эту версию.
//
// Имена ключей — ровно те же, что у /api/settings (port/web.cpp): один словарь
// на прошивку, страницу и запись в NVS.
#pragma once
#include <stddef.h>

#include "settings.h"

namespace core {

enum class LoadResult {
    Ok,          // запись текущей версии
    Migrated,    // версия была старее, цепочка прошла — запись надо сохранить заново
    FromFuture,  // запись новее прошивки (откат): цепочку не гоняли, прочли что поняли
    Defaults,    // записи нет или она не разбирается
};

// Возвращает длину записи без нуля; 0 — не поместилось в cap. При нуле
// существующую запись в NVS менять нельзя: обрезанный JSON не разберётся.
size_t settingsToJson(const Settings& s, char* out, size_t cap);

// Стартует с core::Settings{} и перекрывает только присутствующие ключи;
// неизвестные игнорирует, строки обрезает по размеру буфера поля. Значение вне
// допустимого диапазона поле не трогает — так запись из будущего, где у поля
// другие единицы, не превращается в мусор.
LoadResult settingsFromJson(const char* json, size_t len, Settings& s);

}  // namespace core
