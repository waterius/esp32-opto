// Ядро: кто перезагрузил плату в прошлый раз.
//
// Источников три, потому что перезагрузки бывают разные:
//
//   - плановые (смена настроек, кнопка на странице, час без сети, обновление
//     из облака, сброс к заводским) успевают записать причину в NVS прямо из
//     loop() — там же, где и принимается решение;
//   - сторож главного цикла срабатывает уже тогда, когда loop() не жив: писать
//     в NVS из его колбэка нельзя, поэтому он оставляет метку в RTC;
//   - всё остальное — подача питания, просадка, паника, аппаратный сторож —
//     знает только esp_reset_reason().
//
// Приоритет именно в этом порядке: плановая причина точнее аппаратной.
// «Программная перезагрузка» от esp_reset_reason() не говорит ничего.
#pragma once
#include <stdint.h>

namespace core {

enum class RestartReason : uint8_t {
    Unknown = 0,
    Settings,      // сохранили настройки, требующие перезапуска
    WebButton,     // кнопка «Перезагрузить» на странице статуса
    NoNetwork,     // не было сети дольше rebootMin
    OtaCloud,      // обновление, пришедшее из облака
    OtaWeb,        // обновление со страницы /update
    FactoryReset,  // удержание кнопки BOOT
};

// Текст плановой причины или nullptr, если она неизвестна.
const char* plannedRestartText(RestartReason reason);

// Что показать в логе и на странице статуса.
const char* restartText(RestartReason planned, bool watchdogTripped, const char* hardware);

}  // namespace core
